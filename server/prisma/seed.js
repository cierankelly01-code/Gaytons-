function getCategory(code, name) {
  const n = name.toUpperCase();
  if (code >= 996 && code <= 998) return 'BREADS_SOURDOUGH';
  if (n.includes('SOURDOUGH')) return 'BREADS_SOURDOUGH';
  if (code >= 994 && code <= 1074) return 'BREADS_WHITE';
  if (code >= 1075 && code <= 1133) return 'BREADS_BROWN';
  if (code >= 1135 && code <= 1139) return 'BREADS_SOURDOUGH';
  if (code >= 1134 && code <= 1214) {
    if (code === 1134) return 'ROLLS_BATCHES';
    return 'BREADS_MALTED';
  }
  if (code >= 1215 && code <= 1480) {
    if (n.includes('BURGER') || n.includes('BRIOCHE')) return 'ROLLS_BURGERS';
    if (n.includes('SUB') || n.includes('FRENCH') || n.includes('BATON')) return 'ROLLS_SUBS';
    return 'ROLLS_BATCHES';
  }
  if (code >= 3006 && code <= 3064) return 'SCONES_TEACAKES';
  if (code >= 5025 && code <= 5295) {
    if (n.includes('CATERER')) return 'CAKES_CATERER';
    if (n.includes('TRAYBAKE') || n.includes('SWISS ROLL') || n.includes('CRACKNELL BAKE')) return 'CAKES_TRAYBAKE';
    return 'CAKES_INDIVIDUAL';
  }
  if (code >= 5300 && code <= 5450) return 'PIES';
  if (code >= 6002 && code <= 6218) {
    if (n.includes('TRAYBAKE') || n.includes('FLAPJACK TRAYBAKE') || n.includes('ROCKY ROAD TRAYBAKE') || n.includes('FUDGE BROWNIE TRAYBAKE') || n.includes('BROOKIE TRAYBAKE') || n.includes('BAKEWELL TRAYBAKE')) return 'CAKES_TRAYBAKE';
    return 'PASTRIES_SWEET';
  }
  if (code >= 6950 && code <= 6998) {
    if (n.includes('SAUSAGE ROLL') || n.includes('STEAK BAKE') || n.includes('PASTY') || n.includes('CHEESE & ONION') || n.includes('SAUSAGE BEAN')) return 'PASTRIES_SAVOURY';
    return 'PASTRIES_SWEET';
  }
  if (code >= 7094 && code <= 7096) return 'CAKES_TRAYBAKE';
  return 'BREADS_WHITE';
}

async function main() {
  console.log('Seeding database...');

  await prisma.orderSequence.upsert({
    where: { id: 1 },
    update: {},
    create: { id: 1, nextVal: 1 },
  });

  for (const [code, name, price] of PRODUCTS) {
    const category = getCategory(code, name);
    await prisma.product.upsert({
      where: { productCode: String(code) },
      update: { productName: name, price, category },
      create: {
        productCode: String(code),
        productName: name,
        price,
        category,
      },
    });
  }

  console.log(`Seeded ${PRODUCTS.length} products`);

  const adminPassword = await bcrypt.hash('Admin@Gaytons1', 12);
  await prisma.user.upsert({
    where: { email: 'admin@gaytonsbakery.co.uk' },
    update: {},
    create: {
      email: 'admin@gaytonsbakery.co.uk',
      passwordHash: adminPassword,
      role: 'ADMIN',
      businessName: 'Gaytons Bakery',
      contactName: 'Admin',
      phone: '01234 567890',
      isActive: true,
    },
  });

  console.log('Admin user created: admin@gaytonsbakery.co.uk / Admin@Gaytons1');
  console.log('Seed complete.');
}

main()
  .catch((e) => { console.error(e); process.exit(1); })
  .finally(() => prisma.$disconnect());
